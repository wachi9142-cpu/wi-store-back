import { replyText } from "../client";

export const ADMIN_HELP = `👩‍🍳 คำสั่งแม่ค้า
• สต็อก — ดูยอดคงเหลือ
• เก็กฮวย 30 — เพิ่มสต็อก 30 (พิมพ์หลายบรรทัดได้)
• ลด เก็กฮวย 5 — ลดสต็อก
• ตั้ง เก็กฮวย 0 — ตั้งยอดตรง ๆ
• รอยืนยัน — ดูออเดอร์ที่รอตรวจสลิป
• ยืนยัน #12 — ยืนยันออเดอร์ (ตัดสต็อก)
• ยืนยัน #12 บังคับ — ยืนยันโดยไม่ตัดสต็อก
• ปฏิเสธ #12 เหตุผล — ปฏิเสธออเดอร์
• ปิดร้าน [ข้อความ] — ปิดรับออเดอร์ชั่วคราว
• เปิดร้าน — กลับมารับออเดอร์
• สถานะร้าน — ดูว่าเปิด/ปิด
• ใช้คูปอง ABC123 — ใช้คูปองให้ลูกค้าที่ซื้อหน้าร้าน
• คูปอง 0812345678 — ดูคูปอง/ยอดสะสมของลูกค้า
• เมนู — ดูเมนูแบบที่ลูกค้าเห็น
(เพิ่ม/แก้สินค้า ราคา และสร้างโปรโมชั่น ทำที่หน้าเว็บ)`;

export async function handleAdminHelp(text: string, replyToken: string) {
  if (!/^(ช่วยเหลือ|help|คำสั่ง)$/i.test(text)) return false;
  await replyText(replyToken, ADMIN_HELP);
  return true;
}
